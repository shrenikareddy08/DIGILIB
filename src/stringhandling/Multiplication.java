package stringhandling;

 class Multiplication {
	public int multiply(int x)
	{
		int p;
		p = x * x;
		return p;
	}
    public int multiply(int x , int y)
    {
    	int p;
    	p = x * y;
    	return p;
    }
    public int multiply(int x, int y , int z)
    {
    	int p;
    	p = x*y*z;
    	return p;
    }
    public double multiply(double x, double y)
    {
    	double p = x*y;
    	return p;
    }
}
